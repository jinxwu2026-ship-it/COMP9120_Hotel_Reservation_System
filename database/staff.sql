/* additive web/CLI identity migration; run after schema.sql */
BEGIN;

CREATE TABLE IF NOT EXISTS staff (
  staff_id              INTEGER GENERATED BY DEFAULT AS IDENTITY,
  username              VARCHAR(40) NOT NULL,
  display_name          VARCHAR(80) NOT NULL,
  password_hash         TEXT NOT NULL,
  role                  TEXT NOT NULL,
  is_active             BOOLEAN NOT NULL DEFAULT TRUE,
  must_change_password  BOOLEAN NOT NULL DEFAULT TRUE,
  session_version       INTEGER NOT NULL DEFAULT 0,
  failed_attempts       INTEGER NOT NULL DEFAULT 0,
  locked_until          TIMESTAMPTZ,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (staff_id),
  UNIQUE (username),
  CHECK (username ~ '^[a-z0-9_.-]{3,40}$'),
  CHECK (display_name ~ '[^[:space:]]'),
  CHECK (password_hash ~ '^scrypt:'),
  CHECK (role IN ('receptionist', 'manager')),
  CHECK (session_version >= 0),
  CHECK (failed_attempts >= 0),
  CHECK (locked_until IS NULL OR isfinite(locked_until)),
  CHECK (isfinite(created_at))
);

COMMIT;
