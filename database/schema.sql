BEGIN;

/* create the schema */
CREATE TABLE guest (
  guest_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
  name          TEXT NOT NULL,
  email         TEXT,
  phone         TEXT NOT NULL,
  PRIMARY KEY (guest_id),
  CHECK (name ~ '[^[:space:]]'),
  CHECK (phone ~ '[^[:space:]]')
);

CREATE TABLE room_type (
  room_type_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
  type_name          TEXT NOT NULL,
  max_guests         INTEGER NOT NULL,
  base_nightly_rate  NUMERIC(10,2) NOT NULL,
  PRIMARY KEY (room_type_id),
  UNIQUE (type_name),
  CHECK (type_name ~ '[^[:space:]]'),
  CHECK (max_guests > 0),
  CHECK (base_nightly_rate >= 0 AND base_nightly_rate <> 'NaN'::numeric)
);

CREATE TABLE room (
  room_id              INTEGER GENERATED BY DEFAULT AS IDENTITY,
  room_number          TEXT NOT NULL,
  room_type_id         INTEGER NOT NULL,
  is_bookable          BOOLEAN NOT NULL DEFAULT TRUE,
  housekeeping_status  TEXT NOT NULL,
  PRIMARY KEY (room_id),
  UNIQUE (room_number),
  FOREIGN KEY (room_type_id) REFERENCES room_type(room_type_id) ON DELETE RESTRICT,
  CHECK (room_number ~ '[^[:space:]]'),
  CHECK (housekeeping_status IN ('clean', 'dirty', 'cleaning'))
);

CREATE TABLE reservation (
  reservation_id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
  guest_id                 INTEGER NOT NULL,
  room_id                  INTEGER NOT NULL,
  check_in_date            DATE NOT NULL,
  check_out_date           DATE NOT NULL,
  guest_count              INTEGER NOT NULL,
  booked_nightly_rate      NUMERIC(10,2) NOT NULL,
  created_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status                   TEXT NOT NULL DEFAULT 'confirmed',
  actual_check_in_at       TIMESTAMPTZ,
  actual_check_out_at      TIMESTAMPTZ,
  previous_reservation_id  INTEGER,
  PRIMARY KEY (reservation_id),
  FOREIGN KEY (guest_id) REFERENCES guest(guest_id) ON DELETE RESTRICT,
  FOREIGN KEY (room_id) REFERENCES room(room_id) ON DELETE RESTRICT,
  FOREIGN KEY (previous_reservation_id) REFERENCES reservation(reservation_id) ON DELETE RESTRICT,
  CHECK (isfinite(check_in_date)),
  CHECK (isfinite(check_out_date)),
  CHECK (guest_count > 0),
  CHECK (booked_nightly_rate >= 0 AND booked_nightly_rate <> 'NaN'::numeric),
  CHECK (isfinite(created_at)),
  CHECK (status IN ('confirmed', 'cancelled', 'checked_in', 'checked_out')),
  CONSTRAINT reservation_date_order CHECK (check_out_date > check_in_date),
  CONSTRAINT reservation_not_self CHECK (previous_reservation_id <> reservation_id),
  CONSTRAINT reservation_actual_times CHECK (
    (status IN ('confirmed', 'cancelled')
      AND actual_check_in_at IS NULL AND actual_check_out_at IS NULL)
    OR (status = 'checked_in'
      AND actual_check_in_at IS NOT NULL AND isfinite(actual_check_in_at)
      AND actual_check_out_at IS NULL)
    OR (status = 'checked_out'
      AND actual_check_in_at IS NOT NULL AND isfinite(actual_check_in_at)
      AND actual_check_out_at IS NOT NULL AND isfinite(actual_check_out_at)
      AND actual_check_out_at >= actual_check_in_at)
  )
);

CREATE TABLE reservation_guest (
  reservation_guest_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
  reservation_id        INTEGER NOT NULL,
  full_name             TEXT NOT NULL,
  PRIMARY KEY (reservation_guest_id),
  FOREIGN KEY (reservation_id) REFERENCES reservation(reservation_id) ON DELETE RESTRICT,
  CHECK (full_name ~ '[^[:space:]]')
);

/* cancelled attempts remain in history; a predecessor has at most one other successor */
CREATE UNIQUE INDEX uq_reservation_successor
  ON reservation (previous_reservation_id)
  WHERE previous_reservation_id IS NOT NULL AND status <> 'cancelled';

/* actual occupancy is different from planned date availability */
CREATE UNIQUE INDEX uq_room_checked_in
  ON reservation (room_id) WHERE status = 'checked_in';

/* shortcut: this index only speeds up searches; overlap prevention needs the shared Room lock protocol */
CREATE INDEX ix_reservation_active_dates
  ON reservation (room_id, check_in_date, check_out_date)
  WHERE status IN ('confirmed', 'checked_in');
CREATE INDEX ix_reservation_contact ON reservation (guest_id);
CREATE INDEX ix_reservation_guest_parent ON reservation_guest (reservation_id);

COMMIT;
