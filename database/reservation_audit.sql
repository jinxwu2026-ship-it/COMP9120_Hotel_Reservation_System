CREATE TABLE IF NOT EXISTS reservation_audit (
  audit_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
  reservation_id  INTEGER NOT NULL,
  staff_id        INTEGER,
  source          TEXT NOT NULL,
  action          TEXT NOT NULL,
  occurred_at     TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  reason          TEXT NOT NULL DEFAULT '',
  before_data     JSONB,
  after_data      JSONB NOT NULL,
  PRIMARY KEY (audit_id),
  FOREIGN KEY (reservation_id) REFERENCES reservation(reservation_id) ON DELETE RESTRICT,
  FOREIGN KEY (staff_id) REFERENCES staff(staff_id) ON DELETE RESTRICT,
  CONSTRAINT reservation_audit_source_check
    CHECK (source IN ('staff', 'developer_customer', 'database', 'public_booking')),
  CONSTRAINT reservation_audit_actor_check CHECK (
    (source = 'staff' AND staff_id IS NOT NULL) OR (source <> 'staff' AND staff_id IS NULL)),
  CHECK (action IN ('create', 'amend', 'discount', 'cancel', 'add_guest',
      'remove_guest', 'check_in', 'check_out', 'create_continuation', 'activate_continuation')),
  CHECK (isfinite(occurred_at)),
  CHECK (char_length(reason) <= 500),
  CHECK (before_data IS NULL OR jsonb_typeof(before_data) = 'object'),
  CHECK (jsonb_typeof(after_data) = 'object')
);

